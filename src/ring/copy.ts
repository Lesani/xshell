export type CopyKey = keyof typeof C;

// `{name}` interpolation. Unknown placeholders are left as they are.
export function fmtc(key: CopyKey, params?: Record<string, string | number>): string {
  const s: string = C[key];
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

// The keys that come as a `.one`/`.other` pair.
type Counted = { [K in CopyKey]: K extends `${infer B}.one` ? (`${B}.other` extends CopyKey ? B : never) : never }[CopyKey];

// `base.one` when n is exactly 1, else `base.other`, with `{n}` filled.
export function plural(base: Counted, n: number, params?: Record<string, string | number>): string {
  return fmtc((n === 1 ? `${base}.one` : `${base}.other`) as CopyKey, { n, ...params });
}
